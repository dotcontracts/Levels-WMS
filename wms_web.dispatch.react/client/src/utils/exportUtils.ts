export const exportExpensesToPDF = (
  expenses: DailyExpense[],
  options: ExportOptions = {}
) => {
  const {
    title = 'Expense Management Report',
    filename = `expenses-export-${new Date().toISOString().split('T')[0]}.pdf`,
    includeFilters = false,
    filterSummary = ''
  } = options;

  const doc = new jsPDF('landscape', 'mm', 'a4');

  doc.setFontSize(18);
  doc.setFont('helvetica', 'bold');
  doc.text(title, 14, 20);

  doc.setFontSize(11);
  doc.setFont('helvetica', 'normal');
  doc.text('Ficma Home Logistics Dispatch System', 14, 28);

  const exportDate = new Date().toLocaleDateString('en-US', {
    year: 'numeric', month: 'long', day: 'numeric', hour: '2-digit', minute: '2-digit'
  });
  doc.text(`Exported on: ${exportDate}`, 14, 34);

  let yPosition = 40;
  if (includeFilters && filterSummary) {
    doc.setFontSize(9);
    doc.setFont('helvetica', 'italic');
    doc.text(`Filters Applied: ${filterSummary}`, 14, yPosition);
    yPosition += 6;
  }

  const totalAmount = expenses.reduce((s, e) => s + e.amount, 0);
  const approvedTotal = expenses.filter(e => e.status === 'approved').reduce((s, e) => s + e.amount, 0);
  const pendingTotal = expenses.filter(e => e.status === 'pending').reduce((s, e) => s + e.amount, 0);

  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  doc.text(
    `Records: ${expenses.length}  |  Total: KES ${totalAmount.toLocaleString()}  |  Approved: KES ${approvedTotal.toLocaleString()}  |  Pending: KES ${pendingTotal.toLocaleString()}`,
    14,
    yPosition
  );
  yPosition += 6;

  const tableHeaders = ['Date', 'Category', 'Description', 'Vendor', 'Amount (KES)', 'Status', 'Requested By', 'Branch', 'Clerk', 'Approved By'];

  const tableData = expenses.map(exp => [
    formatExpenseDate(exp.date),
    exp.category.replace(/_/g, ' ').replace(/\b\w/g, c => c.toUpperCase()),
    exp.description,
    exp.vendor || 'N/A',
    exp.amount.toLocaleString(),
    exp.status.charAt(0).toUpperCase() + exp.status.slice(1),
    exp.createdByName || 'N/A',
    exp.branchName || 'N/A',
    exp.clerkName || 'N/A',
    exp.approvedByName || 'N/A'
  ]);

  autoTable(doc, {
    head: [tableHeaders],
    body: tableData,
    startY: yPosition,
    rowPageBreak: 'avoid',
    styles: { fontSize: 7.5, cellPadding: 2 },
    headStyles: { fillColor: [41, 128, 185], textColor: 255, fontStyle: 'bold' },
    alternateRowStyles: { fillColor: [245, 245, 245] },
    columnStyles: {
      0: { cellWidth: 20 },
      1: { cellWidth: 24 },
      2: { cellWidth: 40 },
      3: { cellWidth: 22 },
      4: { cellWidth: 22 },
      5: { cellWidth: 18 },
      6: { cellWidth: 24 },
      7: { cellWidth: 22 },
      8: { cellWidth: 24 },
      9: { cellWidth: 24 }
    },
    margin: { left: 14, right: 14 },
    didDrawPage: (data) => {
      const pageCount = (doc as any).internal.getNumberOfPages();
      doc.setFontSize(8);
      doc.setFont('helvetica', 'normal');
      doc.text(
        `Page ${data.pageNumber} of ${pageCount}`,
        doc.internal.pageSize.width - 30,
        doc.internal.pageSize.height - 10
      );
    }
  });

  doc.save(filename);
};